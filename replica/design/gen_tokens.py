#!/usr/bin/env python3
"""Regenerates tokens.css and tailwind.config.js from tokens.json + tokens.dark.json."""
import json, os
os.chdir(os.path.dirname(os.path.abspath(__file__)))
L = json.load(open('tokens.json')); D = json.load(open('tokens.dark.json'))
roles = list(L['color'])
def vars_(t, ind): return "\n".join(f"{ind}--color-{k}: {v};" for k, v in t['color'].items())
css = f"""/* Generated by gen_tokens.py from tokens.json / tokens.dark.json. Edit the JSON, not this file. */
:root {{
  color-scheme: light;
{vars_(L,'  ')}
  --font-display: {L['font']['display']};
  --font-sans: {L['font']['sans']};
  --font-mono: {L['font']['mono']};
{chr(10).join(f'  --space-{i}: {v}px;' for i, v in enumerate(L['space']))}
{chr(10).join(f'  --radius-{k}: {v}px;' for k, v in L['radius'].items())}
{chr(10).join(f'  --border-{k}: {v}px;' for k, v in L['border'].items())}
  --motion-fast: {L['motion']['fast']};
  --motion-base: {L['motion']['base']};
  --motion-ease: {L['motion']['ease']};
  --content-width: {L['layout']['content']}px;
  --gutter: {L['layout']['gutter']}px;
  --corner-marker: {L['layout']['corner-marker']}px;
}}
@media (prefers-color-scheme: dark) {{
  :root:not([data-theme="light"]) {{
    color-scheme: dark;
{vars_(D,'    ')}
  }}
}}
[data-theme="dark"] {{
  color-scheme: dark;
{vars_(D,'  ')}
}}
@media (prefers-reduced-motion: reduce) {{
  *, *::before, *::after {{ animation: none !important; transition: none !important; }}
}}
"""
open('tokens.css', 'w').write(css)
names = {'text-muted': 'muted'}
colors = "\n".join(f"        '{names.get(k,k)}': 'var(--color-{k})'," for k in roles)
open('tailwind.config.js', 'w').write(f"""// Generated colour block + type/space mapping. Components use bg-surface, text-muted, bg-accent, never raw hex.
// Colours point at CSS variables, so light/dark switching needs no `dark:` variants.
// Use text-accent-text for red TEXT; bg-accent is for fills with text-on-accent.
/** @type {{import('tailwindcss').Config}} */
export default {{
  theme: {{
    extend: {{
      colors: {{
{colors}
      }},
      fontFamily: {{ display: ['var(--font-display)'], sans: ['var(--font-sans)'], mono: ['var(--font-mono)'] }},
      fontSize: {{
        xs: ['12px', {{ lineHeight: '18px', fontWeight: '700' }}],
        sm: ['14px', {{ lineHeight: '21px', fontWeight: '600' }}],
        'body-sm': ['15px', {{ lineHeight: '22px' }}],
        base: ['16px', {{ lineHeight: '24px' }}],
        lg: ['22px', {{ lineHeight: '24px' }}],
        xl: ['28px', {{ lineHeight: '29px' }}],
        display: ['clamp(40px, 8vw, 76px)', {{ lineHeight: '1.02' }}],
        score: ['clamp(34px, 7vw, 64px)', {{ lineHeight: '1' }}],
        label: ['12px', {{ lineHeight: '18px', letterSpacing: '0.08em' }}],
      }},
      spacing: {{ 1.5: '6px', 2.5: '10px', 3.5: '14px' }},
      borderRadius: {{ xs: '4px', sm: '6px', md: '8px', lg: '10px', xl: '14px' }},
      borderWidth: {{ DEFAULT: '1px', control: '1.5px', 2: '2px', 3: '3px', 4: '4px' }},
      maxWidth: {{ content: '980px', feed: '640px', dialog: '460px' }},
      screens: {{ stack: {{ max: '780px' }} }},
      transitionDuration: {{ fast: '250ms', base: '400ms' }},
    }},
  }},
}};
""")
