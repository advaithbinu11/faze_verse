import { lazy, Suspense } from 'react';
import { Link } from 'react-router';
import { buttonStyles } from '../ui/primitives.jsx';
import { useAuth } from '../state/AuthContext.jsx';
import events from '../data/recent-events.json'; // generated by `npm run events` from the FaZe Lobby html
import MeetTheTeam from './MeetTheTeam.jsx';

const VaultScene = lazy(() => import('../three/VaultScene.jsx'));

// [title, body, link, link text]. Each link says what you do there, since two pillars share the Live page.
const PILLARS = [
  ['Post', 'Share your take on the match, reply to other fans and keep the conversation going on the feed. Your first 3 posts earn 3 points each.', '/feed', 'Post on the feed'],
  ['Watch', 'Keep a registered video playing to the end and the points land in your balance, once per video.', '/live', 'Watch and earn points'],
  ['Party up', 'Join a squad and a voice chat for any game. Players who own the same games and follow the same teams come first.', '/party', 'Find a party'],
];

// An event flagged upcoming stops being "upcoming" once its day has passed. `when` has no year ("Sun Nov 15"),
// so it is read against the current one; a date that does not parse keeps its flag.
function isUpcoming(e) {
  if (!e.upcoming) return false;
  const day = Date.parse(`${e.when.replace(/^\w{3},?\s+(?=\w{3}\s)/, '')} ${new Date().getFullYear()}`);
  if (Number.isNaN(day)) return true;
  const today = new Date(); today.setHours(0, 0, 0, 0);
  return day >= today.getTime();
}

export default function Home() {
  const { user, status } = useAuth();
  return (
    <>
      {/* The hero is always dark, in both themes, so the shader backdrop and the text contrast never depend on the page theme. */}
      <section data-theme="dark" className="relative isolate mx-[calc(var(--page-gutter)*-1)] lg:group-data-[sidebar=true]/shell:ml-0 mb-10 overflow-hidden bg-bg text-text" style={{ minHeight: 480 }}>
        <Suspense fallback={null}>
          <VaultScene className="absolute inset-0 -z-10" />
        </Suspense>
        <div className="gutter flex min-h-[480px] max-w-[640px] flex-col justify-center gap-5 py-12">
          <h1 className="text-display">Watch.<br />Post.<br /><span className="text-accent-text">Party up.</span></h1>
          <p className="max-w-[44ch] text-body-sm text-text">Earn points watching FaZe, post and talk with other fans on the feed, and party up with players who own the same games.</p>
          {/* Visitors get the way in; signed-in players get the features. Nothing renders while the session loads, so the buttons never flip. */}
          {status !== 'loading' && (user ? (
            <div className="flex flex-wrap gap-2.5">
              <Link to="/live" className={buttonStyles('primary')}>Go to the live match</Link>
              <Link to="/party" className={buttonStyles('secondary', '!bg-transparent')}>Find a party</Link>
            </div>
          ) : (
            <div className="flex flex-wrap gap-2.5">
              <Link to="/signup" className={buttonStyles('primary')}>Sign up free</Link>
              <a href="#how-h" className={buttonStyles('secondary', '!bg-transparent')}>How it works</a>
            </div>
          ))}
        </div>
      </section>

      <section aria-labelledby="how-h" className="mb-12 scroll-mt-4">
        <h2 id="how-h" className="mb-3 text-xl">How it works</h2>
        <ul className="m-0 grid list-none gap-4 p-0 sm:grid-cols-3">
          {PILLARS.map(([t, body, to, label]) => (
            <li key={t} className="rounded-lg border-2 border-text p-3.5">
              <h3 className="text-lg">{t}</h3>
              <p className="mt-1 text-body-sm text-muted">{body}</p>
              <Link to={to} className="mt-1 inline-flex min-h-[44px] items-center text-sm font-bold text-accent-text underline">{label}</Link>
            </li>
          ))}
        </ul>
      </section>

      <section aria-labelledby="events-h" className="mb-12">
        <h2 id="events-h" className="mb-3 text-xl">Recent events</h2>
        {events.length === 0 ? <p className="text-body-sm text-muted">No recent events right now. Check back after the next match.</p> : (
        <ul className="m-0 grid list-none gap-4 p-0 sm:grid-cols-2 lg:grid-cols-4">
          {events.map((e) => (
            <li key={e.id} className={`frame flex flex-col gap-1.5 p-4 ${isUpcoming(e) ? 'bg-surface' : ''}`}>
              <div className="flex items-center gap-2">
                <span className="label">{e.when}</span>
                {isUpcoming(e) && <span className="rounded-xs bg-accent px-1.5 text-xs text-on-accent">Upcoming</span>}
              </div>
              <h3 className="break-words text-lg">{e.title}</h3>
              <p className="text-body-sm text-muted">{e.detail}</p>
            </li>
          ))}
        </ul>
        )}
      </section>

      <MeetTheTeam />

      {status !== 'loading' && !user && (
        <section aria-labelledby="join-h" className="frame mt-12 grid gap-3 p-6 sm:p-8">
          <h2 id="join-h" className="text-xl sm:text-[40px] sm:leading-[44px]">Join the Vault</h2>
          <p className="m-0 max-w-[52ch] text-body-sm text-muted">Free to join. Post on the feed, talk with other fans, and your first squad is a few clicks away. You also start with a welcome bonus of points.</p>
          <div><Link to="/signup" className={buttonStyles('primary')}>Sign up free</Link></div>
        </section>
      )}
    </>
  );
}
